// Optional browser QA: npm install --no-save playwright, then node tests/browser-smoke.cjs.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const base = process.env.PREVIEW_URL || 'http://127.0.0.1:3000';
const out = path.join(__dirname,'..','tmp');
const fs = require('node:fs');fs.mkdirSync(out,{recursive:true});
(async () => {
  const browser = await chromium.launch({headless:true,channel:process.env.BROWSER_CHANNEL || 'msedge'});
  try {
    const context = await browser.newContext({viewport:{width:1440,height:1000}});
    const page = await context.newPage();
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto(base,{waitUntil:'networkidle'});
    await page.waitForSelector('.product-card');
    assert.equal(await page.locator('#productGrid .product-card').count(),12);
    assert.equal(await page.title(),'AUTORA — аксесуари для твого авто');
    await page.locator('#searchInput').fill('videoreiestrator');
    assert.ok(await page.locator('#productGrid .product-card').count()>0);
    await page.locator('#searchInput').fill('неіснуючий товар 5555555');
    assert.equal(await page.locator('#emptyState').isVisible(),true);
    await page.locator('#resetSearch').click();
    await page.locator('#loadMore').click();
    assert.equal(await page.locator('#productGrid .product-card').count(),24);
    await page.locator('[data-category="Для подорожей"]').click();
    assert.match(await page.locator('#resultsCount').innerText(),/18/);
    await page.locator('[data-category="Усі товари"]').click();
    await page.locator('#sortSelect').selectOption('price-asc');
    assert.match(await page.locator('#productGrid .product-title').first().innerText(),/тримач телефону на дефлектор/);
    await page.locator('#productGrid [data-favorite="1"]').click();
    await page.locator('#openFavorites').click();
    assert.equal(await page.locator('#productGrid .product-card').count(),1);
    await page.reload();await page.waitForSelector('.product-card');
    assert.equal(await page.locator('#favoritesCount').innerText(),'1');
    await page.locator('[data-category="Усі товари"]').click();
    await page.locator('#sortSelect').selectOption('price-asc');
    await page.locator('#productGrid [data-add="1"]').click();
    await page.locator('#openCart').click();
    await page.locator('#cartItems [data-delta="1"]').click();
    assert.match(await page.locator('#cartTotal').innerText(),/610/);
    await page.locator('#checkoutButton').click();
    await page.locator('[name="name"]').fill('Тест інтерфейсу');
    await page.locator('[name="phone"]').fill('+380671112233');
    await page.locator('[name="delivery"]').fill('Київ, тестове відділення');
    await page.locator('.checkout-submit').click();
    await page.waitForSelector('.payment-card-number');
    assert.equal(await page.locator('.payment-card-number').innerText(),'4035 2000 4449 4893');
    assert.match(await page.locator('#checkoutResult').innerText(),/ФОП Мільшин М.О./);
    await page.screenshot({path:path.join(out,'checkout.png')});
    await page.locator('#closeResult').click();
    const productLink=page.locator('#productGrid [data-product-link="1"]').first();
    await productLink.click();
    assert.match(page.url(),/\/tovar\//);
    await page.reload();await page.waitForSelector('.product-detail-copy');
    assert.match(await page.locator('#productPage h1').innerText(),/тримач телефону/);
    await page.locator('[data-photo-zoom]').click();
    assert.equal(await page.locator('#photoZoomDialog').isVisible(),true);
    await page.locator('#closePhotoZoom').click();
    await page.locator('#focusSearch').click();
    await page.locator('#searchInput').fill('Гачки');
    await page.locator('#productGrid [data-product-link="11"]').first().click();
    await page.locator('#productPage .detail-favorite').click();
    await page.waitForURL('**/staff-console');
    await page.waitForSelector('#loginPanel:not([hidden])');
    if (process.env.PREVIEW_ADMIN_PASSWORD) {
      await page.locator('#adminPassword').fill(process.env.PREVIEW_ADMIN_PASSWORD);
      await page.locator('#loginForm button').click();
      await page.waitForSelector('#adminDashboard:not([hidden])');
      assert.equal(await page.locator('#statementTableBody tr').count(),339);
      await page.locator('#statementSearch').fill('877.00');
      assert.ok(await page.locator('#statementTableBody tr').count()>0);
      await page.locator('#statementClearFilters').click();
      const statementDownload = page.waitForEvent('download');
      await page.locator('#statementExportButton').click();
      const downloadedStatement = await statementDownload;
      const exportedStatement = fs.readFileSync(await downloadedStatement.path(),'utf8');
      assert.ok(exportedStatement.includes('AU-ST-01-01'));
      await page.screenshot({path:path.join(out,'admin.png')});
      await page.setViewportSize({width:390,height:844});
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'mobile admin overflow');
      await page.screenshot({path:path.join(out,'admin-mobile.png')});
      await page.setViewportSize({width:1440,height:1000});
      await page.locator('#siteOrdersTab').click();
      const row = page.locator('#ordersTableBody tr').filter({hasText:'Тест інтерфейсу'}).first();
      await row.locator('.status-select').selectOption('processing');
      await page.waitForSelector('.orders-notice:not([hidden])');
      await page.reload();await page.waitForSelector('#adminDashboard:not([hidden])');
      await page.locator('#logoutButton').click();
      await page.waitForSelector('#loginPanel:not([hidden])');
      assert.equal(await page.locator('#loginPanel').isVisible(),true);
    }
    await page.goto(base,{waitUntil:'networkidle'});
    await page.evaluate(async()=>{for(let y=0;y<document.body.scrollHeight;y+=650){scrollTo(0,y);await new Promise(r=>setTimeout(r,40))}scrollTo(0,0)});
    await page.locator('.product-photo').evaluateAll(async images=>Promise.all(images.map(img=>img.decode().catch(()=>{}))));
    await page.screenshot({path:path.join(out,'desktop.png'),fullPage:true});
    await page.screenshot({path:path.join(out,'desktop-top.png')});
    for(const width of [320,390,768,1024,1440]){
      await page.setViewportSize({width,height:844});
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,`overflow at ${width}`);
    }
    await page.setViewportSize({width:390,height:844});
    await page.locator('#menuToggle').click();
    assert.equal(await page.locator('.main-nav').isVisible(),true);
    await page.locator('#menuToggle').click();
    await page.screenshot({path:path.join(out,'mobile.png'),fullPage:true});
    await page.screenshot({path:path.join(out,'mobile-top.png')});
    await page.locator('#productGrid [data-add]').first().click();
    await page.locator('#openCart').click();
    assert.equal(await page.locator('#cartDrawer').getAttribute('aria-hidden'),'false');
    await page.locator('#checkoutButton').click();
    assert.equal(await page.locator('#checkoutForm').isVisible(),true,'a new checkout remains usable after a completed order');
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'mobile checkout overflow');
    await page.screenshot({path:path.join(out,'checkout-mobile.png')});
    await page.locator('#closeCheckout').click();
    assert.deepEqual(errors,[]);
    console.log('Browser QA passed: search/transliteration, empty results, filters, sort, pagination, favorites persistence, cart, checkout/payment, product URLs/reload, image zoom, hidden admin/login/history/status/logout, responsive widths 320/390/768/1024/1440.');
    await context.close();
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
